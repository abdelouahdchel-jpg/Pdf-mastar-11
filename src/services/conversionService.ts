import { renderAsync } from 'docx-preview';
import html2canvas from 'html2canvas';
import { PDFDocument } from 'pdf-lib';
import * as pdfjsLib from 'pdfjs-dist';
import {
  Document,
  Paragraph,
  TextRun,
  Table,
  TableRow,
  TableCell,
  HeadingLevel,
  Packer,
  BorderStyle,
  WidthType,
  PageBreak,
} from 'docx';
import { extractTextFromPdf } from './pdfService';

if (typeof window !== 'undefined' && !pdfjsLib.GlobalWorkerOptions.workerSrc) {
  pdfjsLib.GlobalWorkerOptions.workerSrc = '/pdf.worker.min.mjs';
}

/**
 * Generate high-fidelity PDF from Word (.docx) document
 * Preserves Arabic text, RTL direction, English text, headings, tables, and embedded images.
 * Note: Legacy .doc (Word 97-2003 binary format) is not supported.
 */
export async function convertWordToPdf(
  file: File,
  onProgress?: (progress: { stage: string; percent: number }) => void
): Promise<{ blob: Blob; fileName: string }> {
  const lowerName = file.name.toLowerCase();
  if (lowerName.endsWith('.doc') && !lowerName.endsWith('.docx')) {
    throw new Error(
      'Legacy Word 97-2003 (.doc) binary format is not supported. Please open the file in Microsoft Word, Google Docs, or LibreOffice and save it as modern OpenXML (.docx) before converting.'
    );
  }

  const baseName = file.name.replace(/\.[^/.]+$/, '');

  if (typeof window !== 'undefined' && typeof document !== 'undefined') {
    if (onProgress) onProgress({ stage: 'Unpacking Word document & initializing layout engine...', percent: 15 });

    const container = document.createElement('div');
    container.id = 'docx-pdf-render-stage';
    // Style container off-screen but visible so html2canvas can measure layout
    container.style.position = 'fixed';
    container.style.left = '-99999px';
    container.style.top = '0';
    container.style.width = '820px';
    container.style.backgroundColor = '#ffffff';
    container.style.zIndex = '-9999';
    container.style.visibility = 'visible';
    document.body.appendChild(container);

    try {
      if (onProgress) onProgress({ stage: 'Rendering typography, Arabic RTL text, tables, and images...', percent: 35 });

      await renderAsync(file, container, undefined, {
        inWrapper: true,
        breakPages: true,
        useBase64URL: true,
        renderHeaders: true,
        renderFooters: true,
        ignoreWidth: false,
        ignoreHeight: false,
      });

      // Wait for any embedded images to finish decoding
      const imgElements = Array.from(container.querySelectorAll('img'));
      if (imgElements.length > 0) {
        if (onProgress) onProgress({ stage: `Decoding ${imgElements.length} embedded images...`, percent: 50 });
        await Promise.all(
          imgElements.map(
            (img) =>
              new Promise((resolve) => {
                if (img.complete) {
                  resolve(null);
                } else {
                  img.onload = () => resolve(null);
                  img.onerror = () => resolve(null);
                  setTimeout(() => resolve(null), 1500); // 1.5s timeout safety
                }
              })
          )
        );
      }

      // Query page sections generated by docx-preview
      let pageSections = Array.from(
        container.querySelectorAll<HTMLElement>('.docx-wrapper > section.docx, section.docx')
      );
      if (pageSections.length === 0) {
        pageSections = [container];
      }

      const totalPages = pageSections.length;
      const pdfDoc = await PDFDocument.create();

      for (let i = 0; i < totalPages; i++) {
        if (onProgress) {
          onProgress({
            stage: `Capturing layout for PDF page ${i + 1} of ${totalPages}...`,
            percent: Math.round(55 + ((i + 1) / totalPages) * 35),
          });
        }

        const section = pageSections[i];
        const canvas = await html2canvas(section, {
          scale: 1.5,
          useCORS: true,
          logging: false,
          backgroundColor: '#ffffff',
        });

        const jpgDataUrl = canvas.toDataURL('image/jpeg', 0.92);
        const res = await fetch(jpgDataUrl);
        const imgBytes = await res.arrayBuffer();
        const embeddedImg = await pdfDoc.embedJpg(imgBytes);

        // Standard PDF points (72 pt/in vs 96 px/in)
        const pdfWidth = (canvas.width / 1.5) * 0.75;
        const pdfHeight = (canvas.height / 1.5) * 0.75;

        const page = pdfDoc.addPage([pdfWidth, pdfHeight]);
        page.drawImage(embeddedImg, {
          x: 0,
          y: 0,
          width: pdfWidth,
          height: pdfHeight,
        });
      }

      if (onProgress) onProgress({ stage: 'Compiling PDF document...', percent: 98 });
      const pdfBytes = await pdfDoc.save({ useObjectStreams: true });
      const blob = new Blob([new Uint8Array(pdfBytes)], { type: 'application/pdf' });
      return { blob, fileName: `${baseName}.pdf` };
    } finally {
      if (container.parentNode) {
        document.body.removeChild(container);
      }
    }
  }

  throw new Error('Browser environment required for Word document conversion.');
}

/**
 * Convert PDF into a genuine, valid Microsoft Word (.docx) document
 * Preserves paragraph breaks, headings, detected tables, and page breaks.
 * Rejects scanned / image-only PDFs with a clear message explaining that OCR is required.
 */
export async function convertPdfToWord(
  file: File,
  onProgress?: (progress: { stage: string; percent: number }) => void
): Promise<{ blob: Blob; fileName: string }> {
  if (onProgress) onProgress({ stage: 'Reading PDF document structure...', percent: 15 });

  const bytes = await file.arrayBuffer();
  const loadingTask = pdfjsLib.getDocument({ data: new Uint8Array(bytes) });
  const pdf = await loadingTask.promise;
  const numPages = pdf.numPages;

  let totalChars = 0;
  interface PageLine {
    y: number;
    height: number;
    items: { str: string; x: number; y: number; width: number; height: number }[];
  }
  const pageBlocks: PageLine[][] = [];

  for (let pageNum = 1; pageNum <= numPages; pageNum++) {
    if (onProgress) {
      onProgress({
        stage: `Analyzing text & layout (Page ${pageNum}/${numPages})...`,
        percent: Math.round(15 + (pageNum / numPages) * 35),
      });
    }

    const page = await pdf.getPage(pageNum);
    const textContent = await page.getTextContent();
    const items = textContent.items as any[];

    for (const item of items) {
      if (item.str) totalChars += item.str.trim().length;
    }

    // Sort items: descending by Y, ascending by X
    const sortedItems = [...items].sort((a, b) => {
      const yA = a.transform ? a.transform[5] : 0;
      const yB = b.transform ? b.transform[5] : 0;
      if (Math.abs(yA - yB) > 3.5) {
        return yB - yA;
      }
      const xA = a.transform ? a.transform[4] : 0;
      const xB = b.transform ? b.transform[4] : 0;
      return xA - xB;
    });

    const pageLines: PageLine[] = [];
    for (const item of sortedItems) {
      if (!item.str || !item.str.trim()) continue;
      const x = item.transform ? item.transform[4] : 0;
      const y = item.transform ? item.transform[5] : 0;
      const height = item.height || Math.abs(item.transform ? item.transform[0] : 10);
      const width = item.width || 0;

      const existingLine = pageLines.find((l) => Math.abs(l.y - y) <= 3.5);
      if (existingLine) {
        existingLine.items.push({ str: item.str, x, y, width, height });
      } else {
        pageLines.push({
          y,
          height,
          items: [{ str: item.str, x, y, width, height }],
        });
      }
    }

    pageLines.sort((a, b) => b.y - a.y);
    pageBlocks.push(pageLines);
  }

  // Scanned / Image-only PDF detection
  if (totalChars < 15) {
    throw new Error(
      'No selectable digital text was found in this PDF. This document appears to be a scanned paper copy or image-based PDF. Please use the OCR PDF tool to recognize text from scanned images before converting to Word.'
    );
  }

  if (onProgress) onProgress({ stage: 'Constructing genuine Word (.docx) document...', percent: 65 });

  // Compute median body font size
  const allHeights: number[] = [];
  for (const pLines of pageBlocks) {
    for (const l of pLines) {
      for (const it of l.items) {
        if (it.height > 0) allHeights.push(it.height);
      }
    }
  }
  allHeights.sort((a, b) => a - b);
  const medianHeight = allHeights.length > 0 ? allHeights[Math.floor(allHeights.length / 2)] : 11;

  const docChildren: any[] = [];

  for (let pIdx = 0; pIdx < pageBlocks.length; pIdx++) {
    // Insert page break between pages
    if (pIdx > 0) {
      docChildren.push(new Paragraph({ children: [new PageBreak()] }));
    }

    const lines = pageBlocks[pIdx];
    let i = 0;

    while (i < lines.length) {
      const line = lines[i];

      // Segment line into columns if wide gaps exist (gap > 22 pt)
      const columnSegments: string[] = [];
      let currentSeg = '';
      for (let k = 0; k < line.items.length; k++) {
        const item = line.items[k];
        if (k > 0) {
          const prev = line.items[k - 1];
          const gap = item.x - (prev.x + prev.width);
          if (gap > 22) {
            columnSegments.push(currentSeg.trim());
            currentSeg = item.str;
            continue;
          }
        }
        currentSeg += (currentSeg ? ' ' : '') + item.str;
      }
      if (currentSeg.trim()) columnSegments.push(currentSeg.trim());

      // Table Detection: check if consecutive lines form a tabular grid
      if (columnSegments.length >= 2) {
        const tableCandidateRows: string[][] = [];
        let lookAhead = i;

        while (lookAhead < lines.length) {
          const checkLine = lines[lookAhead];
          const cols: string[] = [];
          let seg = '';
          for (let k = 0; k < checkLine.items.length; k++) {
            const it = checkLine.items[k];
            if (k > 0) {
              const pr = checkLine.items[k - 1];
              const g = it.x - (pr.x + pr.width);
              if (g > 22) {
                cols.push(seg.trim());
                seg = it.str;
                continue;
              }
            }
            seg += (seg ? ' ' : '') + it.str;
          }
          if (seg.trim()) cols.push(seg.trim());

          if (cols.length >= 2) {
            tableCandidateRows.push(cols);
            lookAhead++;
          } else {
            break;
          }
        }

        // If at least 2 consecutive multi-column lines exist, build an actual Word Table
        if (tableCandidateRows.length >= 2) {
          const maxCols = Math.max(...tableCandidateRows.map((r) => r.length));
          const docxRows = tableCandidateRows.map((rowCells, rIndex) => {
            const cells: TableCell[] = [];
            for (let c = 0; c < maxCols; c++) {
              const cellText = rowCells[c] || '';
              cells.push(
                new TableCell({
                  children: [
                    new Paragraph({
                      children: [
                        new TextRun({
                          text: cellText,
                          bold: rIndex === 0,
                          size: 20, // 10 pt
                        }),
                      ],
                    }),
                  ],
                  borders: {
                    top: { style: BorderStyle.SINGLE, size: 1, color: 'D1D5DB' },
                    bottom: { style: BorderStyle.SINGLE, size: 1, color: 'D1D5DB' },
                    left: { style: BorderStyle.SINGLE, size: 1, color: 'D1D5DB' },
                    right: { style: BorderStyle.SINGLE, size: 1, color: 'D1D5DB' },
                  },
                })
              );
            }
            return new TableRow({ children: cells });
          });

          docChildren.push(
            new Table({
              width: { size: 100, type: WidthType.PERCENTAGE },
              rows: docxRows,
            })
          );
          docChildren.push(new Paragraph({ text: '', spacing: { after: 120 } }));
          i = lookAhead;
          continue;
        }
      }

      // Heading or Paragraph
      const lineText = line.items.map((it) => it.str).join(' ').trim();
      const maxItemHeight = Math.max(...line.items.map((it) => it.height));
      const isHeading = maxItemHeight >= medianHeight * 1.28 && lineText.length < 120;

      if (isHeading) {
        docChildren.push(
          new Paragraph({
            text: lineText,
            heading: maxItemHeight >= medianHeight * 1.5 ? HeadingLevel.HEADING_1 : HeadingLevel.HEADING_2,
            spacing: { before: 240, after: 120 },
          })
        );
        i++;
      } else {
        // Collect paragraph lines until a significant vertical gap or heading
        const paraLines: string[] = [lineText];
        let lastY = line.y;
        i++;

        while (i < lines.length) {
          const nextLine = lines[i];
          const nextText = nextLine.items.map((it) => it.str).join(' ').trim();
          const nextHeight = Math.max(...nextLine.items.map((it) => it.height));
          const nextIsHeading = nextHeight >= medianHeight * 1.28 && nextText.length < 120;
          const vGap = lastY - nextLine.y;

          if (nextIsHeading || vGap > medianHeight * 2.2) {
            break;
          }

          paraLines.push(nextText);
          lastY = nextLine.y;
          i++;
        }

        docChildren.push(
          new Paragraph({
            children: [
              new TextRun({
                text: paraLines.join(' '),
                size: Math.round(medianHeight * 2), // font size in half-points
              }),
            ],
            spacing: { after: 140 },
          })
        );
      }
    }
  }

  if (onProgress) onProgress({ stage: 'Serializing OpenXML package (.docx)...', percent: 90 });

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: { top: 720, right: 720, bottom: 720, left: 720 },
          },
        },
        children: docChildren,
      },
    ],
  });

  const rawBlob = await Packer.toBlob(doc);
  const docxBlob = new Blob([await rawBlob.arrayBuffer()], {
    type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  });

  const baseName = file.name.replace(/\.[^/.]+$/, '');
  return { blob: docxBlob, fileName: `${baseName}_converted.docx` };
}

/**
 * Generate CSV / Excel table from PDF text
 */
export async function convertPdfToExcel(
  file: File,
  onProgress?: (progress: { stage: string; percent: number }) => void
): Promise<{ blob: Blob; fileName: string }> {
  if (onProgress) onProgress({ stage: 'Scanning PDF text and table delimiters...', percent: 45 });
  const { text } = await extractTextFromPdf(file);

  if (onProgress) onProgress({ stage: 'Formatting rows and columns for spreadsheet...', percent: 85 });

  const lines = text.split('\n');
  const csvRows: string[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Detect multiple spaces or tabs as column delimiters
    const columns = trimmed.split(/\t|\s{2,}/);
    const escapedCols = columns.map((col) => `"${col.replace(/"/g, '""').trim()}"`);
    csvRows.push(escapedCols.join(','));
  }

  const csvContent = '\ufeff' + csvRows.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const baseName = file.name.replace(/\.[^/.]+$/, '');

  return { blob, fileName: `${baseName}_data.csv` };
}

/**
 * Convert PDF to standalone HTML web page
 */
export async function convertPdfToHtml(
  file: File,
  onProgress?: (progress: { stage: string; percent: number }) => void
): Promise<{ blob: Blob; fileName: string }> {
  if (onProgress) onProgress({ stage: 'Extracting content layout...', percent: 50 });
  const { text } = await extractTextFromPdf(file);

  const baseName = file.name.replace(/\.[^/.]+$/, '');
  const paragraphs = text
    .split('\n\n')
    .map((block) => `<p style="margin-bottom: 1em; line-height: 1.6;">${escapeHtml(block).replace(/\n/g, '<br/>')}</p>`)
    .join('');

  const htmlDoc = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(baseName)}</title>
  <style>
    body {
      font-family: system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      max-width: 800px;
      margin: 40px auto;
      padding: 0 20px;
      color: #1e293b;
      background-color: #f8fafc;
    }
    .document-card {
      background: #ffffff;
      padding: 40px;
      border-radius: 8px;
      box-shadow: 0 4px 6px -1px rgb(0 0 0 / 0.1);
      border: 1px solid #e2e8f0;
    }
    h1 { color: #dc2626; font-size: 24px; border-bottom: 2px solid #fee2e2; padding-bottom: 12px; }
    p { font-size: 15px; }
  </style>
</head>
<body>
  <div class="document-card">
    <h1>${escapeHtml(baseName)}</h1>
    ${paragraphs}
  </div>
</body>
</html>`;

  const blob = new Blob([htmlDoc], { type: 'text/html;charset=utf-8' });
  return { blob, fileName: `${baseName}.html` };
}

/**
 * Convert PDF to PowerPoint Slide Deck representation (.html slides)
 */
export async function convertPdfToPowerPoint(
  file: File,
  onProgress?: (progress: { stage: string; percent: number }) => void
): Promise<{ blob: Blob; fileName: string }> {
  if (onProgress) onProgress({ stage: 'Generating presentation slides...', percent: 50 });
  const { text } = await extractTextFromPdf(file);
  const baseName = file.name.replace(/\.[^/.]+$/, '');

  const pages = text.split(/--- Page \d+ ---/).filter((p) => p.trim());
  const slidesHtml = pages
    .map((content, idx) => {
      const lines = content.trim().split('\n').filter(Boolean);
      const title = lines[0] || `Slide ${idx + 1}`;
      const bullets = lines.slice(1, 8);

      return `
      <section class="slide">
        <div class="slide-header">
          <span class="slide-num">Slide ${idx + 1}</span>
          <h2>${escapeHtml(title)}</h2>
        </div>
        <div class="slide-body">
          <ul>
            ${bullets.map((b) => `<li>${escapeHtml(b)}</li>`).join('')}
          </ul>
        </div>
      </section>
    `;
    })
    .join('');

  const presentationHtml = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${escapeHtml(baseName)} - Presentation</title>
  <style>
    body { font-family: 'Helvetica Neue', Arial, sans-serif; background: #0f172a; margin: 0; padding: 40px 20px; display: flex; flex-direction: column; align-items: center; gap: 30px; }
    .slide { width: 900px; max-width: 95vw; aspect-ratio: 16 / 9; background: white; border-radius: 12px; box-shadow: 0 10px 25px rgba(0,0,0,0.3); padding: 40px 50px; box-sizing: border-box; display: flex; flex-direction: column; }
    .slide-header { border-bottom: 3px solid #dc2626; padding-bottom: 12px; margin-bottom: 24px; position: relative; }
    .slide-num { font-size: 12px; text-transform: uppercase; color: #dc2626; font-weight: bold; }
    h2 { margin: 6px 0 0; color: #1e293b; font-size: 24px; }
    .slide-body { flex: 1; font-size: 18px; color: #334155; line-height: 1.6; }
    ul { padding-left: 24px; }
    li { margin-bottom: 12px; }
  </style>
</head>
<body>
  ${slidesHtml}
</body>
</html>`;

  const blob = new Blob([presentationHtml], { type: 'text/html;charset=utf-8' });
  return { blob, fileName: `${baseName}_presentation.html` };
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
